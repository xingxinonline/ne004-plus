/*
 * Flash Loader with Position Independent Code (PIC) Demo
 * Main program runs in SRAM1, loads and executes flash ops in SRAM0
 * 
 * Architecture:
 *   SRAM1 (0x20000000): Main control program
 *   SRAM0 (0x1FFF0000): Dynamically loaded flash operation functions
 * 
 * Based on OpenOCD STMQSPI flash loader concept
 */

#include "s300.h"
#include <stdio.h>
#include <string.h>
#include <stdint.h>

#include "rcc.h"
#include "gpio.h"
#include "uart.h"
#include "board.h"
#include "qspi_cadence.h"

/* Memory regions */
#define SRAM0_BASE      0x1FFF0000u
#define SRAM0_SIZE      (192 * 1024u)
#define SRAM1_BASE      0x20000000u
#define SRAM1_SIZE      (64 * 1024u)

/* Flash operation function signatures */
typedef int (*flash_read_fn_t)(uint32_t addr, uint8_t *buf, uint32_t len, uint32_t qspi_base);
typedef int (*flash_write_fn_t)(uint32_t addr, const uint8_t *buf, uint32_t len, uint32_t qspi_base);
typedef int (*flash_erase_fn_t)(uint32_t addr, uint32_t type, uint32_t qspi_base);
typedef uint32_t (*crc32_fn_t)(const uint8_t *data, uint32_t len);

/* Include the auto-generated flash_ops.inc */
/* This is generated by: make flash_ops.inc */
/* For now, we'll use a placeholder structure */

static const uint8_t flash_ops_code[] = {
    /* This will be populated by build system from flash_ops.bin */
    /* Placeholder - real code will be inserted by Makefile */
    0x00, 0x00, 0x00, 0x00
};

#define FLASH_OPS_SIZE  sizeof(flash_ops_code)

/* Control structure in SRAM1 */
typedef struct {
    uint32_t sram0_load_addr;       /* Where we load code in SRAM0 */
    flash_read_fn_t read_fn;
    flash_write_fn_t write_fn;
    flash_erase_fn_t erase_fn;
    crc32_fn_t crc32_fn;
    uint32_t qspi_base;
} flash_loader_ctx_t;

static flash_loader_ctx_t g_ctx;

/* Load flash ops code into SRAM0 and resolve function pointers */
static int flash_loader_init(void)
{
    printf("[LOADER] Initializing Flash Loader (PIC)\r\n");
    printf("[LOADER] SRAM0: 0x%08lX, size: %lu bytes\r\n", 
           (unsigned long)SRAM0_BASE, (unsigned long)SRAM0_SIZE);
    printf("[LOADER] SRAM1: 0x%08lX, size: %lu bytes\r\n",
           (unsigned long)SRAM1_BASE, (unsigned long)SRAM1_SIZE);
    
    /* Choose load address in SRAM0 (aligned) */
    g_ctx.sram0_load_addr = SRAM0_BASE + 0x1000;  /* Leave some space */
    
    /* Check if flash_ops code fits */
    if (FLASH_OPS_SIZE > SRAM0_SIZE - 0x1000) {
        printf("[LOADER] ERROR: flash_ops code too large (%lu bytes)\r\n",
               (unsigned long)FLASH_OPS_SIZE);
        return -1;
    }
    
    printf("[LOADER] Loading flash_ops to 0x%08lX (%lu bytes)\r\n",
           (unsigned long)g_ctx.sram0_load_addr, (unsigned long)FLASH_OPS_SIZE);
    
    /* Copy flash_ops code to SRAM0 */
    memcpy((void *)g_ctx.sram0_load_addr, flash_ops_code, FLASH_OPS_SIZE);
    
    /* Resolve function pointers (offset from load address) */
    /* In PIC code, we need to get the function table first */
    typedef uint32_t* (*get_table_fn_t)(void);
    get_table_fn_t get_table = (get_table_fn_t)(g_ctx.sram0_load_addr | 1); /* Thumb bit */
    
    /* For now, use fixed offsets (this should match flash_ops.S layout) */
    /* Real implementation would parse the function table */
    g_ctx.read_fn = (flash_read_fn_t)((g_ctx.sram0_load_addr + 0x00) | 1);
    g_ctx.write_fn = (flash_write_fn_t)((g_ctx.sram0_load_addr + 0x40) | 1);
    g_ctx.erase_fn = (flash_erase_fn_t)((g_ctx.sram0_load_addr + 0xC0) | 1);
    g_ctx.crc32_fn = (crc32_fn_t)((g_ctx.sram0_load_addr + 0x100) | 1);
    
    g_ctx.qspi_base = g_qspi.reg_base;
    
    printf("[LOADER] Function pointers:\r\n");
    printf("  read:  0x%08lX\r\n", (unsigned long)g_ctx.read_fn);
    printf("  write: 0x%08lX\r\n", (unsigned long)g_ctx.write_fn);
    printf("  erase: 0x%08lX\r\n", (unsigned long)g_ctx.erase_fn);
    printf("  crc32: 0x%08lX\r\n", (unsigned long)g_ctx.crc32_fn);
    
    /* Flush instruction cache if applicable */
    __DSB();
    __ISB();
    
    printf("[LOADER] Init complete\r\n");
    return 0;
}

