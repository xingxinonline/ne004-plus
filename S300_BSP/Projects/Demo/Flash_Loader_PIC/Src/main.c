int main(void)
{
    board_init();
    
    uint32_t ahb_hz = rcc_get_clock(RCC_CLOCK_AHB);
    uint32_t sclk_hz = ahb_hz / 2u;
    
    printf("\r\n");
    printf("============================================\r\n");
    printf(" S300 Flash Loader - Position Independent  \r\n");
    printf("   Based on OpenOCD STMQSPI Architecture   \r\n");
    printf("============================================\r\n");
    printf("AHB Clock:  %lu Hz\r\n", (unsigned long)ahb_hz);
    printf("QSPI Clock: %lu Hz\r\n", (unsigned long)sclk_hz);
    printf("\r\n");
    
    /* Initialize QSPI controller */
    qspi_set_verbose(false);
    qspi_cadence_init(ahb_hz, sclk_hz);
    
    /* Initialize flash loader */
    if (flash_loader_init() != 0) {
        printf("[MAIN] Flash loader init failed\r\n");
        return -1;
    }
    
    /* Run tests */
    flash_loader_test();
    
    /* Interactive command loop */
    printf("\r\n[MAIN] Entering command loop\r\n");
    printf("Commands:\r\n");
    printf("  read ADDR LEN  - Read from flash\r\n");
    printf("  info           - Show loader info\r\n");
    printf("  help           - Show this help\r\n");
    
    char line[128];
    while (1) {
        printf("\r\n> ");
        
        /* Simple command input (blocking) */
        int n = 0;
        while (n < sizeof(line) - 1) {
            uint16_t ch = uart_read(UART_IDX3, UARTTYPE_STD_SERIAL);
            char c = (char)(ch & 0xFF);
            if (c == '\r') continue;
            if (c == '\n') break;
            line[n++] = c;
        }
        line[n] = '\0';
        
        if (strcmp(line, "info") == 0) {
            printf("Flash Loader Info:\r\n");
            printf("  SRAM0 Load: 0x%08lX\r\n", (unsigned long)g_ctx.sram0_load_addr);
            printf("  Code Size:  %lu bytes\r\n", (unsigned long)FLASH_OPS_SIZE);
            printf("  QSPI Base:  0x%08lX\r\n", (unsigned long)g_ctx.qspi_base);
        } else if (strcmp(line, "help") == 0) {
            printf("Commands:\r\n");
            printf("  read ADDR LEN  - Read from flash\r\n");
            printf("  info           - Show loader info\r\n");
            printf("  help           - Show this help\r\n");
        } else if (strncmp(line, "read ", 5) == 0) {
            unsigned long addr = 0, len = 0;
            if (sscanf(line + 5, "%lx %lu", &addr, &len) == 2) {
                if (len > 256) len = 256;
                uint8_t buf[256];
                int rc = g_ctx.read_fn((uint32_t)addr, buf, (uint32_t)len, g_ctx.qspi_base);
                printf("Read result: %d\r\n", rc);
                if (rc == 0) {
                    for (uint32_t i = 0; i < len; i++) {
                        if (i % 16 == 0) printf("\r\n%08lX: ", (unsigned long)(addr + i));
                        printf("%02X ", buf[i]);
                    }
                    printf("\r\n");
                }
            } else {
                printf("Usage: read ADDR LEN\r\n");
            }
        } else if (n > 0) {
            printf("Unknown command: %s\r\n", line);
        }
    }
    
    return 0;
}
